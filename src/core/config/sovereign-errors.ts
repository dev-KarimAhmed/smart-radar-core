/**
 * دالة المطابقة والترجمة السيادية (SSOT Interpreter)
 */
export function interpretSovereignError(code: string): SovereignErrorDefinition {
  const normalizedCode = code && code.trim().toUpperCase();
  if (normalizedCode && SOVEREIGN_ERR_DICTIONARY[normalizedCode]) {
    return SOVEREIGN_ERR_DICTIONARY[normalizedCode];
  }
  
  // دمج مع أخطاء النظام السحابي العامة لتوفير مرونة تامة
  return {
    code: 'SYS-UNKNOWN',
    name: 'عطل فني غير مصنف (Unclassified System Pulse)',
    description: `حدث خلل غير متوقع بكود الإشارة: ${code || 'UNKNOWN'}. يرجى فحص نبض النواة الفنية.`,
    action: 'تسجيل النبضة محلياً، وإرسال تقرير تشخيصي مؤمن لغرفة العمليات للمعايرة.'
  };
}
